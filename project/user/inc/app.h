#ifndef _app_h_
#define _app_h_

/**
 * @file app.h
 * @brief 用户应用层入口。
 *
 * `main.c` 只负责底层启动和主循环，本模块负责把设置、屏幕、菜单、VOFA、
 * OpenART 轮询和底盘测试等应用任务收敛到统一入口。
 */

/**
 * @brief 初始化用户应用层。
 *
 * 依次初始化系统时间基准、掉电设置、屏幕、VOFA、底盘测试和菜单状态。
 * 调用前应完成系统时钟、调试串口、OpenART UART、底盘控制和执行器初始化，
 * 这样菜单首次刷新时读取到的控制/通信状态已经处于可用状态。
 *
 * @note 仅在主程序初始化阶段调用一次；函数内部不得等待外设数据或依赖 ISR 已经开始调度。
 * @warning 若调整初始化顺序，需要同时检查 `time_ms()`、菜单按键消抖和屏幕首次绘制的依赖关系。
 */
void app_init(void);

/**
 * @brief 轮询用户应用层任务。
 *
 * 主循环反复调用该函数，用于处理菜单、VOFA、OpenART 协议帧和底盘测试任务。
 * 这些任务共享无线串口、屏幕和控制状态，只允许做短时间轮询，把控制实时性留给 PIT ISR。
 *
 * @note 该函数必须保持非阻塞；新增任务不得在这里等待串口、延时或做长时间求解。
 * @warning 主循环卡住虽然不会直接停止 PIT 中断，但会拖慢菜单刷新、OpenART 地图确认和 VOFA 遥控超时处理。
 */
void app_poll(void);

#endif
